import { uuid } from "@/lib/generators";
import type { AuditAction, AuditEvent, User } from "@/types";

export function auditEvent(
  actor: Pick<User, "id" | "firstName" | "lastName" | "role">,
  action: AuditAction,
  entity: string,
  description: string,
  at: string,
  record?: { id?: string; label?: string },
): AuditEvent {
  return {
    id: uuid(),
    userId: actor.id,
    userName: `${actor.firstName} ${actor.lastName}`,
    role: actor.role,
    action,
    entity,
    recordId: record?.id,
    recordLabel: record?.label,
    description,
    timestamp: at,
  };
}

